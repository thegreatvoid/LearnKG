"""Builds data_output/eval_framework/REPORT.md from the JSON/CSV outputs of the framework (no hand-typed numbers).

  python -m kg_eval.framework.report
"""

import json
import math

import pandas as pd

from .common import KGS, OUT, RELATION_TYPES


def load(rel):
    return json.loads((OUT / rel).read_text())


def f(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "–"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def ci(v, nd=2):
    return f"[{f(v[0], nd)}, {f(v[1], nd)}]" if v and v[0] == v[0] else ""


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    C = load("concepts/concepts_report.json")
    P = load("prerequisite/prerequisite_report.json")
    R = load("relations/relation_checks_report.json")
    W = load("weights/weights_report.json")
    B = load("bigs/bigs_by_relation.json")
    G = load("gap_proxy/gap_proxy_report.json")
    A = load("annotation/relations/build_summary.json")
    kgs = list(KGS)
    L = []
    w = L.append
    w("# Knowledge-graph evaluation report (CK-12 Basic Geometry)\n")
    w("Generated by `python -m kg_eval.framework.report` from the files in `data_output/eval_framework/`. "
      "One textbook only: nothing here shows generalisation. Evaluation kinds are labelled: **[GT]** ground truth "
      "(independent labels), **[AUTO]** automatic consistency checks, **[GROUND]** textual grounding, "
      "**[EXPL]** exploratory diagnostics, **[NOT DONE]** cannot be performed yet.\n")

    # 1. executive summary
    pr = {k: P["kgs"][k]["common_set"] for k in kgs}
    bo = pr["rule_v3"]
    wr = W["prerequisite_ranking"]["rule_v3"]["methods"]
    w("## 1. Executive summary\n")
    w(f"- **Prerequisite [GT]** (AL-CPL, {P['common_set_pairs']} pairs covered by every KG): the extracted "
      f"prerequisite edges of the rule-based and LLM KGs are near chance (ROC-AUC {f(pr['rule_v3']['auc_kg_score']['auc'])}, "
      f"{f(pr['kgx_v2']['auc_kg_score']['auc'])}; edge recall {f(pr['rule_v3']['kg_edge']['recall'])}, "
      f"{f(pr['kgx_v2']['kg_edge']['recall'])}). The hybrid KG reaches closure F1 {f(pr['kgx_v2_hybrid']['kg_closure']['f1'])} "
      f"and AUC {f(pr['kgx_v2_hybrid']['auc_kg_score']['auc'])}, but it is built from book order, and book order alone "
      f"scores F1 {f(bo['book_order']['f1'])}, AUC {f(bo['auc_book_order']['auc'])}.")
    w(f"- **Direction [GT]**: book order puts the prerequisite first for "
      f"{bo['direction']['book_order']['correct']}/{bo['direction']['book_order']['decided']} AL-CPL positives; extracted "
      f"edges decide too few gold pairs to judge (rule_v3 {pr['rule_v3']['direction']['kg_edges']['decided']}, "
      f"kgx_v2 {pr['kgx_v2']['direction']['kg_edges']['decided']}).")
    w(f"- **Other relation types**: no independent labels exist, so no precision/recall is reported. Automatic "
      f"diagnostics [AUTO] find many contradictions (section 6). An annotation package of {A['items']} blind items is ready.")
    w(f"- **AHP weight [GT, prerequisite ranking only]**: NDCG@10 {f(wr['AHP (0.52S+0.24C+0.09P+0.15E)']['ndcg@10']['mean'])} "
      f"vs random {f(wr['random']['ndcg@10']['mean'])}; co-occurrence alone {f(wr['C only (min(1,n/3))']['ndcg@10']['mean'])}, "
      f"book order {f(wr['book order (gap)']['ndcg@10']['mean'])}. The weight is symmetric "
      f"(max |w(A,B) − w(B,A)| = {W['symmetry']['max_abs_difference']}), so it cannot judge direction, and it is unvalidated for "
      f"the other four types.")
    gp = G["kgs"]
    w(f"- **Gap proxy [GT, concept level]**: following the rule-based or LLM KG's prerequisite graph finds few AL-CPL "
      f"prerequisites (lower-bound P@5 {f(gp['rule_v3']['direct_lower_bound']['kg_graph']['p@5']['mean'])} / "
      f"{f(gp['kgx_v2']['direct_lower_bound']['kg_graph']['p@5']['mean'])}); book order "
      f"{f(gp['rule_v3']['direct_lower_bound']['book_order']['p@5']['mean'])}. Question-level gap detection [NOT DONE]: "
      f"no question set exists.")
    w("")

    # 2. datasets
    w("## 2. Dataset inventory and limitations\n")
    w(table(["Data", "Used for", "Independent?", "Limitations"], [
        ["AL-CPL geometry (`geometry.pairs`/`.preqs`)", "prerequisite [GT]", "yes (external annotators, Wikipedia concepts)",
         f"{P['gold']['pairs']} pairs, {P['gold']['positives']} positive; prerequisite only; positives are already transitively closed; names matched heuristically (hand-written geometry synonym map)"],
        ["AL-CPL concept list (89)", "concept coverage [GT, partial]", "yes", "covers few of the book's concepts: recall of these 89 only, no precision"],
        ["`gold_pairs.csv` (133)", "annotation pilot only", "no", "one author, no guideline, positives only, inconsistent direction; re-annotated in the package"],
        ["Part-of / Application / Similarity / Extension labels", "–", "–", "none exist [NOT DONE]"],
        ["Question set for gap detection", "–", "–", "none exists [NOT DONE]"],
    ]))
    w("")

    # 3. concepts
    w("## 3. Concept extraction [GT partial]\n")
    rows = []
    for k in kgs:
        c = C[k]
        rows.append([k, c["n_concepts"], f"{c['alcpl_matched']}/{c['alcpl_concepts']}", c["alcpl_matched_high_conf"],
                     f"{c['positive_pairs_with_missing_concept']}/{c['positive_pairs_total']}",
                     f(c["max_prerequisite_recall_given_concepts"]), c["kg_concepts_in_hard_coded_list"],
                     f"{c['definitions_valid']}/{c['definitions_total']}"])
    w(table(["KG", "concepts", "AL-CPL matched", "high-conf", "AL-CPL positives touching a missing concept",
             "max reachable prereq. recall", "concepts also in the rule pipeline's hard-coded list (overlap; kg_extract does not use the list)",
             "valid definitions"], rows))
    w("\nMissing AL-CPL concepts by where they occur in the book (absent = not in the textbook at all: a reference/book "
      "mismatch, not an extraction error):\n")
    w(table(["KG", "absent from book", "in book body", "heading only"],
            [[k, C[k]["missing_by_cause"].get("absent", 0), C[k]["missing_by_cause"].get("body", 0),
              C[k]["missing_by_cause"].get("heading_only", 0)] for k in kgs]))
    w("\nInvestigated terms (present in KG? / where in the book / why absent):\n")
    rows = []
    for t in C["rule_v3"]["investigated_terms"]:
        row = [t["term"], t["in_book"], "yes" if t["in_hard_coded_list"] else ""]
        for k in ("rule_v3", "kgx_v2"):
            x = next(i for i in C[k]["investigated_terms"] if i["term"] == t["term"])
            row.append("present" if x["present"] else x["reason_if_absent"])
        rows.append(row)
    w(table(["term", "in book", "in hard-coded list", "rule_v3", "kgx_v2 (= hybrid)"], rows))
    w("\nThe rule-based KG's coverage of these terms comes largely from its hard-coded geometry vocabulary, which will "
      "not transfer to another subject. Concept precision/recall over the book needs the concept annotation in "
      "`annotation/concepts/` [NOT DONE].\n")

    # 4. inventory
    w("## 4. Edge inventory per KG and relation type\n")
    rows = []
    for k in kgs:
        bt = R["kgs"][k]["by_type"]
        rows.append([k] + [bt[t]["edges"] for t in RELATION_TYPES] + [sum(bt[t]["edges"] for t in RELATION_TYPES)])
    w(table(["KG"] + RELATION_TYPES + ["total"], rows))
    w("\nCo-occurrence is not a relation type in either pipeline (only these five types exist). It is used to generate "
      "candidates (kg_extract pairs; the rule pipeline's keyword path needs both concepts in one sentence) and as the C "
      "weight factor. Similarity is stored once per pair (A→B); the HTML graph builder adds the reverse edge for display.\n")

    # 5. prerequisite
    w("## 5. Prerequisite benchmark [GT]\n")
    w(f"Common set: {P['common_set_pairs']} AL-CPL pairs covered by every KG (CIs: bootstrap over query concepts). "
      "Unmatched pairs are reported as coverage loss, not negatives; KG edges between pairs AL-CPL never labelled are unknown.\n")
    rows = []
    for k in kgs:
        c = pr[k]
        e, cl, rk = c["kg_edge"], c["kg_closure"], c["ranking_kg_score"]
        rows.append([k + (" (circular vs book order)" if P["kgs"][k]["uses_book_order"] else ""),
                     f"{f(e['precision'])} / {f(e['recall'])} / {f(e['f1'])}", f"{f(cl['f1'])} {ci(cl['f1_ci95'])}",
                     f"{f(c['auc_kg_score']['auc'])} {ci(c['auc_kg_score']['auc_ci95'])}",
                     f"{f(rk['ndcg@5'])} / {f(rk['ndcg@10'])}", f"{f(rk['p@5'])} / {f(rk['r@10'])}",
                     f"{c['direction']['kg_edges']['correct']}/{c['direction']['kg_edges']['decided']}",
                     P["kgs"][k]["prerequisite_edges_unlabelled_in_alcpl"],
                     f(P["kgs"][k]["end_to_end_recall_all_positives"]["closure"])])
    rows.append(["book order (rule_v3 positions)", f"{f(bo['book_order']['precision'])} / {f(bo['book_order']['recall'])} / {f(bo['book_order']['f1'])}",
                 "", f"{f(bo['auc_book_order']['auc'])} {ci(bo['auc_book_order']['auc_ci95'])}",
                 f"{f(bo['ranking_book_order']['ndcg@5'])} / {f(bo['ranking_book_order']['ndcg@10'])}",
                 f"{f(bo['ranking_book_order']['p@5'])} / {f(bo['ranking_book_order']['r@10'])}",
                 f"{bo['direction']['book_order']['correct']}/{bo['direction']['book_order']['decided']}", "", ""])
    rows.append(["random", f"{f(bo['random_expected']['precision'])} / 0.500 / {f(bo['random_expected']['f1'])} (expected)", "",
                 "0.500", f"{f(bo['ranking_random']['ndcg@5'])} / {f(bo['ranking_random']['ndcg@10'])}",
                 f"{f(bo['ranking_random']['p@5'])} / {f(bo['ranking_random']['r@10'])}", "", "", ""])
    w(table(["KG / method", "edge P / R / F1", "closure F1 [CI]", "ROC-AUC [CI]", "NDCG@5 / @10", "P@5 / R@10",
             "direction correct/decided", "edges unlabelled in AL-CPL", "closure recall over all 524 positives"], rows))
    w("")

    # 6. relation checks
    w("## 6. Automatic validation of all five relation types [AUTO, GROUND]\n")
    w("Diagnostics, not precision/recall. `contradiction` = evidence or structure against the stored edge or direction "
      "(reverse cue, reciprocal directed edge, cycle, AL-CPL negative/reversed, prerequisite introduced after its target, "
      "extension base introduced after the extension); `weak evidence` = no supporting sentence or no explicit cue (also "
      "common for true relations); `semantic` = possible type confusion. Cue checks of rule-KG keyword edges are not "
      "independent (the same kind of cue created them). Grounding = per-edge distance to the nearest sentence (lower = closer).\n")
    for k in kgs:
        w(f"**{k}**" + (" (Prerequisite book-order checks are circular)" if R["kgs"][k]["uses_book_order"] else "") + "\n")
        rows = []
        for t in RELATION_TYPES:
            s = R["kgs"][k]["by_type"][t]
            if not s["edges"]:
                rows.append([t, 0] + [""] * 8)
                continue
            rows.append([t, s["edges"], s["with_support_sentence"], f"{s['cue_supports']}/{s['cue_reverse']}",
                         s["co_occurrence_only"], s["flagged_contradiction"], s["flagged_weak_evidence"],
                         s["flagged_semantic_or_type"], s["structural_violations"], f(s["grounding_distance_median"])])
        w(table(["type", "edges", "with support sentence", "cue supports / reverse", "co-occurrence only",
                 "contradiction", "weak evidence", "semantic/type", "structural", "grounding median"], rows))
        w("")
    w("Notable flags (counts per type are in `relations/relation_checks_report.json`, every edge with its flags in "
      "`relations/edge_checks_<kg>.csv`):\n")
    for k in ("rule_v3", "kgx_v2"):
        for t in RELATION_TYPES:
            s = R["kgs"][k]["by_type"][t]
            if s["edges"]:
                top = sorted(s["flag_counts"].items(), key=lambda x: -x[1])[:4]
                w(f"- {k} {t}: " + ", ".join(f"{a} {b}" for a, b in top))
    w("")
    w("Examples (first flagged with a contradiction / first passing with a supporting cue):\n")
    for k in ("rule_v3", "kgx_v2"):
        for t in RELATION_TYPES:
            s = R["kgs"][k]["by_type"][t]
            for e in s.get("examples_flagged", [])[:1]:
                w(f"- ✗ {k} {t}: *{e['source']} → {e['target']}* ({e['flags']}): \"{e['example_sentence'][:160]}\"")
            for e in s.get("examples_pass", [])[:1]:
                w(f"- ✓ {k} {t}: *{e['source']} → {e['target']}*: \"{e['example_sentence'][:160]}\"")
    w("")

    # 7. weights
    w("## 7. AHP and baseline weights\n")
    w("Prerequisite ranking only [GT]: query = AL-CPL concept, candidates = its labelled candidates, identical for every "
      "method; no coefficient is fitted on these labels. Δ = paired difference vs AHP with bootstrap CI and sign-flip p "
      "(several comparisons, no multiplicity correction).\n")
    for inv in ("rule_v3", "kgx_v2"):
        r = W["prerequisite_ranking"][inv]
        w(f"**Concept inventory {inv}** ({r['queries']} queries, {r['pairs']} pairs, {r['relevant']} relevant)\n")
        rows = []
        for m, v in r["methods"].items():
            rows.append([m, f"{f(v['ndcg@5']['mean'])} {ci(v['ndcg@5']['ci95'])}", f"{f(v['ndcg@10']['mean'])} {ci(v['ndcg@10']['ci95'])}",
                         f(v["p@5"]["mean"]), f(v["r@10"]["mean"]), f(v["pairwise_acc"]["mean"]),
                         f"{v['ndcg@10']['minus_ahp']:+.3f} {ci(v['ndcg@10']['minus_ahp_ci95'], 3)}",
                         f(v["ndcg@10"]["p_sign_flip_vs_ahp"], 4) if v["ndcg@10"]["p_sign_flip_vs_ahp"] is not None else ""])
        w(table(["method", "NDCG@5 [CI]", "NDCG@10 [CI]", "P@5", "R@10", "pairwise acc.", "Δ NDCG@10 vs AHP [CI]", "p"], rows))
        w("")
    w(f"Symmetry: {W['symmetry']['conclusion']} ({W['symmetry']['edges_checked']} edges).\n")
    w("Other relation types [EXPL] (rule_v3 edges; descriptive only, does not establish correctness or educational relevance):\n")
    rows = []
    for t, s in W["other_relation_types_rule_v3"].items():
        if s.get("edges", 0):
            rows.append([t, s["edges"], " / ".join(f(x, 2) for x in s["weight_ahp_quartiles"]),
                         f(s.get("spearman_weight_vs_grounding_distance")), f(s.get("spearman_weight_vs_support_sentences")),
                         f(s.get("spearman_ahp_vs_cooc_only"))])
    w(table(["type", "edges", "AHP weight min/q1/median/q3/max", "ρ(weight, grounding distance)", "ρ(weight, support sentences)",
             "ρ(AHP, C-only)"], rows))
    w("")

    # 8. co-occurrence
    w("## 8. Co-occurrence diagnostics [EXPL]\n")
    for inv in ("rule_v3", "kgx_v2"):
        c = W["cooccurrence"][inv]
        sp = c["spearman"]
        w(f"- {inv}: {c['pairs']} candidate pairs, {c['pairs_with_n0']} never co-occur, {c['pairs_C_saturated']} saturate C. "
          f"ρ(C, candidate frequency) = {f(sp['C_vs_candidate_frequency'])}, ρ(relevance, candidate frequency) = "
          f"{f(sp['relevance_vs_candidate_frequency'])}, ρ(C, E) = {f(sp['C_vs_E'])}, ρ(C, P) = {f(sp['C_vs_P'])}, "
          f"ρ(C, S) = {f(sp['C_vs_S'])}. Hub concepts (top 10% by frequency, ≥ {f(c['hub_threshold_sentences'], 0)} sentences) are "
          f"{f(c['hub_share_all_candidates'])} of candidates, {f(c['hub_share_relevant'])} of relevant candidates and "
          f"{f(c['hub_share_top5_by_C_mean_over_queries'])} of the top 5 by C; relevance rate hub {f(c['relevance_rate_hub'])} vs "
          f"non-hub {f(c['relevance_rate_nonhub'])}.")
    w("\nReading: frequent concepts are more often prerequisites in AL-CPL (foundational concepts are mentioned often), so "
      "part of C's prerequisite signal is concept frequency; frequency-normalised NPMI ranks worse (section 7). This is "
      "a property of prerequisites in this book, not evidence that co-occurrence identifies any relation type.\n")

    # 9. BIGS
    w("## 9. BIGS grounding [GROUND]\n")
    w(f"BIGS→ = coverage of the book's {B['corpus_sentences']} sentences by the triples; BIGS← = how close each triple is to "
      f"some sentence. Lower is better. Size-matched values use random subsets of {B['subset_size']} triples "
      f"({B['draws']} draws); types with fewer triples have full-size values only. BIGS does not measure correctness or direction.\n")
    rows = []
    for k in kgs:
        for t in RELATION_TYPES + ["ALL"]:
            r = B["kgs"][k][t]
            if r["triples"]:
                s = r.get(f"subset_{B['subset_size']}")
                rows.append([k, t, r["triples"], f"{f(r['full']['bigs_to_graph'])} / {f(r['full']['bigs_from_graph'])}",
                             f"{f(s['bigs_to_graph'])} / {f(s['bigs_from_graph'])}" if s else "n < subset size"])
    w(table(["KG", "type", "triples", "full BIGS→ / BIGS←", "size-matched BIGS→ / BIGS←"], rows))
    w("")

    # 10. gap proxy
    w("## 10. Concept-level knowledge-gap proxy [GT, concept level]\n")
    w("For each AL-CPL target concept, every other KG concept is a candidate missing prerequisite. `judged only` drops "
      "candidates AL-CPL never labelled for the target; `lower bound` keeps them as non-relevant. AL-CPL geometry "
      "positives are already transitively closed, so the closure view equals the direct view. This is concept-level "
      "prerequisite ranking, not question-level gap detection.\n")
    rows = []
    for k in kgs:
        gk = gp[k]
        for meth in ("kg_graph", "book_order", "ahp", "c_only", "random"):
            j, lb = gk["direct_judged_only"][meth], gk["direct_lower_bound"][meth]
            rows.append([k if meth == "kg_graph" else "", meth, f"{f(j['p@5']['mean'])} / {f(j['r@10']['mean'])} / {f(j['ndcg@10']['mean'])}",
                         f"{f(lb['p@5']['mean'])} {ci(lb['p@5']['ci95'])} / {f(lb['r@10']['mean'])} / {f(lb['ndcg@10']['mean'])}"])
    w(table(["KG", "method", "judged only: P@5 / R@10 / NDCG@10", "lower bound: P@5 [CI] / R@10 / NDCG@10"], rows))
    w("\nLearning-path validity (top-10 ordered prerequisite-first; share of AL-CPL-labelled ordered pairs respected):\n")
    rows = [[k, m, v["labelled_ordered_pairs"], f(v["share"])] for k in kgs for m, v in gp[k]["learning_path_validity"].items()]
    w(table(["KG", "method", "labelled pairs in paths", "respected"], rows))
    w("\nBook-order paths agree with AL-CPL almost by construction (AL-CPL positives point forward in this book); the "
      "hybrid graph's agreement is circular (built from book order). Rule and LLM graph paths contain almost no labelled "
      "pairs, so their path validity cannot be judged.\n")

    # 11-14
    w("## 11. Failure cases and error analysis\n")
    w("- Concepts: kg_extract drops heading-only terms (SSS, SAS, ASA, AAS, Special Right Triangles) via the frequency "
      "filter and common words (Area, Similarity) via the common-word filter; the rule pipeline drops 2-letter acronyms (HL) "
      "and relies on a hard-coded geometry list.")
    ec = pd.read_csv(OUT / "relations" / "edge_checks_kgx_v2.csv", keep_default_na=False)
    kind = ec[(ec.type == "Part-of") & ec["flags"].str.contains("kind_of_name_pattern")]
    sim = R["kgs"]["rule_v3"]["by_type"]["Similarity"]
    pre2 = R["kgs"]["kgx_v2"]["by_type"]["Prerequisite"]
    w(f"- Prerequisite: extracted edges hit few AL-CPL pairs; {pre2['flag_counts'].get('book_order_backward', 0)} of "
      f"{pre2['edges']} kgx_v2 prerequisite edges point backward in the book.")
    rv = pd.read_csv(OUT.parent / "baseline_v3" / "ck12_geometry" / "relations.csv", keep_default_na=False)
    rs = rv[rv.relation_type == "Similarity"]
    w(f"- Similarity (rule_v3): {sim['flag_counts'].get('possible_congruence_confusion', 0)} of {sim['edges']} edges involve "
      f"congruence wording; {int(rs.evidence.str.lower().str.contains('congruent to').sum())} have evidence containing "
      f"'congruent to', which the keyword path maps to Similarity ({int(rs.sources.str.contains('keyword').sum())} of "
      f"{len(rs)} came from the keyword path).")
    w(f"- Part-of (kgx_v2): {len(kind)} edges have the kind-of name pattern, e.g. " +
      ", ".join(f"*{a} → {b}*" for a, b in zip(kind.source.head(4), kind.target.head(4))) +
      ". Some are genuine type confusions (a kind of X stored as part of X, which is Extension); others are heuristic "
      "false positives (e.g. a property such as an area 'of a circle'). Only annotation can tell them apart.")
    w("- See section 6 and `relations/edge_checks_<kg>.csv` for every flagged edge.\n")
    w("## 12. Claims supported by the evidence\n")
    w("- Supported [GT]: book order is the strongest prerequisite signal in this book; the rule and LLM KGs' prerequisite "
      "edges are near chance on AL-CPL; the AHP weight ranks AL-CPL prerequisites above random, mostly through co-occurrence.")
    w("- Not supported: any precision/recall for Part-of, Application, Similarity or Extension; validity of the AHP weight "
      "for those types or for 'educational relevance'; direction correctness from any weight; question-level gap "
      "detection; generalisation beyond this textbook.\n")
    w("## 13. Annotation requirements for further evaluation\n")
    w(f"- Relations: `annotation/relations/relation_items_BLIND.csv` ({A['items']} items: {json.dumps(A['by_origin'])}), "
      "two independent annotators, Cohen's κ ≥ 0.6, adjudication (guidelines in `annotation/ANNOTATION_GUIDELINES.md`). "
      "Then `annotation_kit evaluate adjudicated.csv` gives per-type TP/FP/FN, P/R/F1 with Wilson CIs on the sample.")
    w("- Concepts: `annotation/concepts/` (8 sections, one per sampled chapter).")
    w("- Questions: 30–50 expert questions with independently listed prerequisites (`annotation/questions/questions_TEMPLATE.csv`).")
    w("- Second domain: `kg_eval/second_domain_protocol.md` (freeze with `kg_eval.freeze_manifest` first).\n")
    w("## 14. Reproducibility\n")
    w("```\npython -m kg_eval.framework.run_all          # every step below, in order\n"
      "python -m kg_eval.framework.concepts_eval\npython -m kg_eval.framework.prereq_eval\n"
      "python -m kg_eval.framework.relation_checks\npython -m kg_eval.framework.weights_eval\n"
      "python -m kg_eval.framework.bigs_by_relation\npython -m kg_eval.framework.gap_proxy\n"
      "python -m kg_eval.framework.annotation_kit build\npython -m kg_eval.framework.report\n"
      "python kg_eval/framework/test_framework.py\n```\n")
    w("Inputs (read-only): " + ", ".join(f"`{KGS[k]['path']}`" for k in kgs) +
      ", `data_input/ck12_geometry/` (textbook, AL-CPL, gold_pairs.csv). Outputs: `data_output/eval_framework/` "
      "(`concepts/`, `prerequisite/`, `relations/`, `weights/`, `bigs/`, `gap_proxy/`, `annotation/`, `REPORT.md`). "
      "Models: `sentence-transformers/all-MiniLM-L6-v2` (BIGS, grounding, definition embeddings).")
    (OUT / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {OUT / 'REPORT.md'}")


if __name__ == "__main__":
    main()
