"""Phase 1: Stage-attrition log for all 524 gold prerequisite pairs.
Records the first stage where each pair is lost:
  1. concept_missing_absent_from_book
  2. concept_missing_present_not_extracted
  3. not_a_candidate
  4. relatedness_filter
  5. top_k_cap
  6. llm_rejection
  7. dag_pruning
  8. direction_wrong
  9. survived_in_graph

Outputs:
  - data_output/stage_attrition_waterfall.json
  - data_output/stage_attrition_pairs_kgx_v2.csv
  - data_output/stage_attrition_pairs_hybrid.csv
  - data_output/stage_attrition_pairs_rule_v3.csv
"""

import json
import sys
from pathlib import Path
from collections import Counter
import pandas as pd
import networkx as nx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kg_eval.framework.common import KG, gold
from kg_eval.data import read_source, split_sentences, term_pattern, concept_terms, first_position

def load_concept_missing_reasons():
    report_path = ROOT / "data_output" / "eval_framework" / "concepts" / "concepts_report.json"
    with open(report_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    missing_map = {}
    for entry in data["kgx_v2"]["missing"]:
        c = entry["alcpl_concept"]
        in_book = entry["in_book"]
        missing_map[c] = "absent" if in_book == "absent" else "present_not_extracted"
    return missing_map

def run_attrition_for_kgx_v2(g_df, missing_map):
    kg = KG("kgx_v2")
    m = kg.gold_matches(g_df)
    
    # Candidate pairs evaluated by LLM
    ps_path = ROOT / "data_output" / "ck12_geometry_kgx_v2" / "pair_scores.csv"
    ps_df = pd.read_csv(ps_path, dtype=str)
    ps_df["score_Prerequisite"] = pd.to_numeric(ps_df["score_Prerequisite"], errors="coerce").fillna(0.0)
    candidates_set = set(zip(ps_df["source_id"], ps_df["target_id"]))
    candidate_prereq_scores = dict(zip(zip(ps_df["source_id"], ps_df["target_id"]), ps_df["score_Prerequisite"]))
    
    # Relations in final KG
    rel_path = ROOT / "data_output" / "ck12_geometry_kgx_v2" / "relations.csv"
    rel_df = pd.read_csv(rel_path, dtype=str)
    all_edges = set(zip(rel_df["source_id"], rel_df["target_id"]))
    pre_edges = set(zip(rel_df[rel_df.relation_type == "Prerequisite"]["source_id"],
                        rel_df[rel_df.relation_type == "Prerequisite"]["target_id"]))

    records = []
    g_pos = g_df[g_df.label == 1].copy()
    
    for _, row in g_pos.iterrows():
        a, b = row["concept"], row["prereq"] # True direction: b -> a (prereq -> concept)
        ca, cb = m[a]["cid"], m[b]["cid"]
        
        rec = {
            "gold_concept": a,
            "gold_prereq": b,
            "true_direction": f"{b} -> {a}",
            "kg_target_id": ca or "",
            "kg_source_id": cb or "",
            "stage_lost": "",
            "details": ""
        }
        
        # Stage 1: Concepts present?
        if not ca or not cb:
            # Determine which is missing and why
            missing_causes = []
            if not ca:
                missing_causes.append(missing_map.get(a, "absent"))
            if not cb:
                missing_causes.append(missing_map.get(b, "absent"))
            
            if "absent" in missing_causes:
                rec["stage_lost"] = "concept_missing_absent_from_book"
                rec["details"] = f"Missing concept absent from textbook text"
            else:
                rec["stage_lost"] = "concept_missing_present_not_extracted"
                rec["details"] = f"Missing concept present in book text but not extracted"
            records.append(rec)
            continue
            
        if ca == cb:
            rec["stage_lost"] = "concept_missing_present_not_extracted"
            rec["details"] = f"Both mapped to identical KG concept {ca}"
            records.append(rec)
            continue
            
        # Both concepts exist in KG: cb (prereq) and ca (target)
        # Stage 2: Candidate Generation
        pair_forward = (cb, ca)
        pair_backward = (ca, cb)
        
        if pair_forward not in candidates_set and pair_backward not in candidates_set:
            rec["stage_lost"] = "not_a_candidate"
            rec["details"] = f"Pair {cb} <-> {ca} not generated by heuristic candidate retriever"
            records.append(rec)
            continue
            
        # Was it considered as forward candidate?
        forward_score = candidate_prereq_scores.get(pair_forward, 0.0)
        backward_score = candidate_prereq_scores.get(pair_backward, 0.0)
        
        # Stage 3: LLM Rejection vs Acceptance
        # In kg_extract, pair classification threshold is >= 0.4
        forward_accepted = (forward_score >= 0.4)
        backward_accepted = (backward_score >= 0.4)
        
        if not forward_accepted and not backward_accepted:
            rec["stage_lost"] = "llm_rejection"
            rec["details"] = f"LLM rejected Prerequisite (score_fwd={forward_score}, score_bwd={backward_score})"
            records.append(rec)
            continue
            
        if not forward_accepted and backward_accepted:
            rec["stage_lost"] = "direction_wrong"
            rec["details"] = f"LLM predicted reverse edge {ca} -> {cb} with score {backward_score}"
            records.append(rec)
            continue
            
        # If forward was accepted by LLM (forward_score >= 0.4):
        # Did it survive into the final relations?
        if pair_forward in pre_edges:
            rec["stage_lost"] = "survived_in_graph"
            rec["details"] = f"Successfully extracted as Prerequisite edge {cb} -> {ca}"
        elif pair_forward in all_edges:
            rec["stage_lost"] = "llm_rejection"
            rec["details"] = f"LLM classified as different relation type in final graph"
        else:
            rec["stage_lost"] = "dag_pruning"
            rec["details"] = f"Forward proposal {cb} -> {ca} was pruned during cycle/DAG resolution"
            
        records.append(rec)
        
    return pd.DataFrame(records)

def run_attrition_for_hybrid(g_df, missing_map):
    kg = KG("kgx_v2_hybrid")
    m = kg.gold_matches(g_df)
    
    text = read_source()
    concepts = kg.concepts
    ids = concepts["concept_id"].tolist()
    terms = concept_terms(concepts)
    pos = {c: first_position(terms[c], text) for c in ids}
    sents = split_sentences(text)
    sets = {}
    for c in ids:
        pats = [p for p in map(term_pattern, terms[c]) if p]
        sets[c] = {i for i, s in enumerate(sents) if any(p.search(s) for p in pats)}
        
    # Hybrid relation edges
    rel_path = ROOT / "data_output" / "ck12_geometry_kgx_v2_hybrid" / "relations.csv"
    rel_df = pd.read_csv(rel_path, dtype=str)
    pre_edges = set(zip(rel_df[rel_df.relation_type == "Prerequisite"]["source_id"],
                        rel_df[rel_df.relation_type == "Prerequisite"]["target_id"]))
                        
    # Load hybrid pair scores
    ps_path = ROOT / "data_output" / "ck12_geometry_kgx_v2_hybrid" / "pair_scores.csv"
    ps_df = pd.read_csv(ps_path, dtype=str)
    ps_df["score_Prerequisite"] = pd.to_numeric(ps_df["score_Prerequisite"], errors="coerce").fillna(0.0)
    scores_dict = dict(zip(zip(ps_df["source_id"], ps_df["target_id"]), ps_df["score_Prerequisite"]))

    # LLM relatedness
    v2_ps = pd.read_csv(ROOT / "data_output" / "ck12_geometry_kgx_v2" / "pair_scores.csv")
    rel_cols = [c for c in v2_ps.columns if c.startswith("score_")]
    v2_ps["tot"] = v2_ps[rel_cols].sum(axis=1)
    llm = {}
    for s, t, v in zip(v2_ps.source_id, v2_ps.target_id, v2_ps.tot):
        llm[frozenset((s, t))] = max(llm.get(frozenset((s, t)), 0.0), float(v))

    records = []
    g_pos = g_df[g_df.label == 1].copy()
    
    for _, row in g_pos.iterrows():
        a, b = row["concept"], row["prereq"]
        ca, cb = m[a]["cid"], m[b]["cid"]
        
        rec = {
            "gold_concept": a,
            "gold_prereq": b,
            "true_direction": f"{b} -> {a}",
            "kg_target_id": ca or "",
            "kg_source_id": cb or "",
            "stage_lost": "",
            "details": ""
        }
        
        if not ca or not cb:
            missing_causes = []
            if not ca:
                missing_causes.append(missing_map.get(a, "absent"))
            if not cb:
                missing_causes.append(missing_map.get(b, "absent"))
            if "absent" in missing_causes:
                rec["stage_lost"] = "concept_missing_absent_from_book"
                rec["details"] = "Missing concept absent from textbook text"
            else:
                rec["stage_lost"] = "concept_missing_present_not_extracted"
                rec["details"] = "Missing concept present in book text but not extracted"
            records.append(rec)
            continue
            
        if ca == cb:
            rec["stage_lost"] = "concept_missing_present_not_extracted"
            rec["details"] = f"Both mapped to identical KG concept {ca}"
            records.append(rec)
            continue
            
        # In hybrid, is direction forward in book order?
        pa, pb = pos.get(ca), pos.get(cb)
        if pa is None or pb is None or pb >= pa:
            rec["stage_lost"] = "direction_wrong"
            rec["details"] = f"Book order inverted or unpositioned: pos({cb})={pb} >= pos({ca})={pa}"
            records.append(rec)
            continue
            
        # Is it related?
        both_sents = len(sets.get(cb, set()) & sets.get(ca, set()))
        rel_score = llm.get(frozenset((cb, ca)), 0.0)
        is_related = (both_sents > 0) or (rel_score > 0)
        if not is_related:
            rec["stage_lost"] = "relatedness_filter"
            rec["details"] = f"No sentence co-occurrence (n=0) and no LLM relatedness (rel=0)"
            records.append(rec)
            continue
            
        # Survived top-k cap?
        # Check if cb -> ca survived into final edges
        if (cb, ca) in pre_edges:
            rec["stage_lost"] = "survived_in_graph"
            rec["details"] = f"Survived into final hybrid graph (top-3 related predecessor)"
        else:
            # Was it dropped by top-k cap or dag cycle removal?
            # In hybrid, cand = sorted list of predecessors for target ca.
            # If cb was not in top-3 -> top_k_cap
            score = scores_dict.get((cb, ca), 0.0)
            # Find all related forward predecessors of ca
            preds = []
            for u in ids:
                if u != ca and pos.get(u) is not None and pos.get(u) < pa:
                    u_both = len(sets.get(u, set()) & sets.get(ca, set()))
                    u_rel = llm.get(frozenset((u, ca)), 0.0)
                    if u_both > 0 or u_rel > 0:
                        preds.append((scores_dict.get((u, ca), 0.0), u))
            preds.sort(reverse=True)
            top3_ids = {u for _, u in preds[:3]}
            if cb not in top3_ids:
                rec["stage_lost"] = "top_k_cap"
                rec["details"] = f"Dropped by predecessor cap k=3 (rank={next(i for i, (_, u) in enumerate(preds, 1) if u == cb)})"
            else:
                rec["stage_lost"] = "dag_pruning"
                rec["details"] = "In top-3 candidates but pruned by cycle removal"
        records.append(rec)
        
    return pd.DataFrame(records)

def run_attrition_for_rule_v3(g_df, missing_map):
    kg = KG("rule_v3")
    m = kg.gold_matches(g_df)
    
    rel_path = ROOT / "data_output" / "baseline_v3" / "ck12_geometry" / "relations.csv"
    rel_df = pd.read_csv(rel_path, dtype=str)
    pre_edges = set(zip(rel_df[rel_df.relation_type == "Prerequisite"]["source_id"],
                        rel_df[rel_df.relation_type == "Prerequisite"]["target_id"]))
    all_edges = set(zip(rel_df["source_id"], rel_df["target_id"]))
    
    # Text sentence index for co-occurrence
    text = read_source()
    concepts = kg.concepts
    ids = concepts["concept_id"].tolist()
    terms = concept_terms(concepts)
    sents = split_sentences(text)
    sets = {}
    for c in ids:
        pats = [p for p in map(term_pattern, terms[c]) if p]
        sets[c] = {i for i, s in enumerate(sents) if any(p.search(s) for p in pats)}

    records = []
    g_pos = g_df[g_df.label == 1].copy()
    
    for _, row in g_pos.iterrows():
        a, b = row["concept"], row["prereq"]
        ca, cb = m[a]["cid"], m[b]["cid"]
        
        rec = {
            "gold_concept": a,
            "gold_prereq": b,
            "true_direction": f"{b} -> {a}",
            "kg_target_id": ca or "",
            "kg_source_id": cb or "",
            "stage_lost": "",
            "details": ""
        }
        
        if not ca or not cb:
            missing_causes = []
            if not ca:
                missing_causes.append(missing_map.get(a, "absent"))
            if not cb:
                missing_causes.append(missing_map.get(b, "absent"))
            if "absent" in missing_causes:
                rec["stage_lost"] = "concept_missing_absent_from_book"
                rec["details"] = "Missing concept absent from textbook text"
            else:
                rec["stage_lost"] = "concept_missing_present_not_extracted"
                rec["details"] = "Missing concept present in book text but not extracted"
            records.append(rec)
            continue
            
        if ca == cb:
            rec["stage_lost"] = "concept_missing_present_not_extracted"
            rec["details"] = f"Both mapped to identical KG concept {ca}"
            records.append(rec)
            continue
            
        # Did they co-occur in any sentence? (Keyword rule candidate requirement)
        both_sents = len(sets.get(cb, set()) & sets.get(ca, set()))
        if both_sents == 0:
            rec["stage_lost"] = "not_a_candidate"
            rec["details"] = "Zero sentence co-occurrences (n=0); rule keyword path requires sentence co-occurrence"
            records.append(rec)
            continue
            
        # If co-occurred: did rule or neural classifier propose it?
        if (cb, ca) in pre_edges:
            rec["stage_lost"] = "survived_in_graph"
            rec["details"] = "Successfully extracted into rule_v3 graph"
        elif (ca, cb) in pre_edges:
            rec["stage_lost"] = "direction_wrong"
            rec["details"] = f"Proposed in reversed direction {ca} -> {cb}"
        elif (cb, ca) in all_edges or (ca, cb) in all_edges:
            rec["stage_lost"] = "llm_rejection"
            rec["details"] = "Proposed as a different relation type (Part-of, Similarity, etc.)"
        else:
            rec["stage_lost"] = "relatedness_filter"
            rec["details"] = "Co-occurred but no prerequisite regex/cue matched"
            
        records.append(rec)
        
    return pd.DataFrame(records)

def main():
    g_df = gold()
    missing_map = load_concept_missing_reasons()
    
    df_kgx = run_attrition_for_kgx_v2(g_df, missing_map)
    df_hybrid = run_attrition_for_hybrid(g_df, missing_map)
    df_rule = run_attrition_for_rule_v3(g_df, missing_map)
    
    out_dir = ROOT / "data_output"
    df_kgx.to_csv(out_dir / "stage_attrition_pairs_kgx_v2.csv", index=False)
    df_hybrid.to_csv(out_dir / "stage_attrition_pairs_hybrid.csv", index=False)
    df_rule.to_csv(out_dir / "stage_attrition_pairs_rule_v3.csv", index=False)
    
    # Compute waterfall summary counts
    stages_order = [
        "concept_missing_absent_from_book",
        "concept_missing_present_not_extracted",
        "not_a_candidate",
        "relatedness_filter",
        "top_k_cap",
        "llm_rejection",
        "dag_pruning",
        "direction_wrong",
        "survived_in_graph"
    ]
    
    waterfall = {
        "total_gold_positive_pairs": len(g_df[g_df.label == 1]),
        "kgx_v2": {s: int((df_kgx.stage_lost == s).sum()) for s in stages_order},
        "kgx_v2_hybrid": {s: int((df_hybrid.stage_lost == s).sum()) for s in stages_order},
        "rule_v3": {s: int((df_rule.stage_lost == s).sum()) for s in stages_order}
    }
    
    waterfall_path = out_dir / "stage_attrition_waterfall.json"
    waterfall_path.write_text(json.dumps(waterfall, indent=2), encoding="utf-8")
    print(f"Wrote waterfall log to {waterfall_path}")
    print(json.dumps(waterfall, indent=2))

if __name__ == "__main__":
    main()
